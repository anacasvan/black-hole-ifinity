// After `vite build`: writes dist/sw.js, a service worker that stores every
// file of the build on the device, so the installed web app works offline.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const dist = path.join(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), 'dist');
const files = [];
const walk = dir => {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (f !== 'sw.js') files.push(path.relative(dist, p).split(path.sep).join('/'));
  }
};
walk(dist);
const hash = crypto.createHash('sha256');
for (const f of files.sort()) hash.update(f).update(fs.readFileSync(path.join(dist, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/sw.mjs — do not edit.
const CACHE = 'bhi-earth-${version}';
const FILES = ${JSON.stringify(['./', ...files.map(f => './' + f)], null, 2)};

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('bhi-earth-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Offline first: answer from the device, fall back to the network.
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  const url = new URL(e.request.url);
  if (url.origin !== self.location.origin) return;
  e.respondWith(
    caches.match(e.request, { ignoreSearch: true, ignoreVary: true }).then(hit => {
      if (hit) return hit;
      if (e.request.mode === 'navigate') return caches.match('./').then(r => r || fetch(e.request));
      return fetch(e.request);
    })
  );
});
`;
fs.writeFileSync(path.join(dist, 'sw.js'), sw);
console.log(`Service worker: ${files.length} files, cache ${version}`);
